let nextReportNumber = 1;
const REPORT_CATEGORIES: ReportCategory[] = CATEGORY_SEEDS.map((category) => ({
  ...category,
  reports: category.reports.map(([name, description]) => {
    const report = { id: `report-${nextReportNumber}`, number: nextReportNumber, name, description };
    nextReportNumber += 1;
    return report;
  })
}));
const TOTAL_REPORT_TEMPLATES = REPORT_CATEGORIES.reduce((count, category) => count + category.reports.length, 0);

type ReportFormatOption = { value: ReportFormat; label: string };
const FORMAT_OPTIONS: ReportFormatOption[] = [
  { value: 'pdf', label: 'PDF Document' },
  { value: 'excel', label: 'Excel Spreadsheet' },
  { value: 'csv', label: 'CSV File' }
];
const FORMAT_LABEL: Record<ReportFormat, string> = { pdf: 'PDF', excel: 'Excel', csv: 'CSV' };
const displayDate = (date: Date) => date.toLocaleDateString('en-GB', { day: '2-digit', month: 'short', year: 'numeric' }).replace(/ /g, '-');
const estimateSize = (format: ReportFormat) => format === 'pdf' ? '850 KB' : format === 'excel' ? '420 KB' : '140 KB';

const reportByNumber = (number: number) => {
  for (const category of REPORT_CATEGORIES) {
    const report = category.reports.find((item) => item.number === number);
    if (report) return { category, report };
  }
  return null;
};

const makeInitialReport = (number: number, generatedBy: string, date: string, format: string, size: string, period: string): ReportRow => {
  const match = reportByNumber(number);
  if (!match) throw new Error(`Missing report template #${number}`);
  return {
    id: `seed-${number}`,
    reportNumber: number,
    name: match.report.name,
    generatedBy,
    date,
    format,
    size,
    category: match.category.label,
    period,
    description: match.report.description,
    status: 'Ready'
  };
};

