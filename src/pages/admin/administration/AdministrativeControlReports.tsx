export function AdministrativeControlReports() {
  const [categoryId, setCategoryId] = useState('');
  const [reportId, setReportId] = useState('');
  const [format, setFormat] = useState<ReportFormat>('pdf');
  const [fromDate, setFromDate] = useState('');
  const [toDate, setToDate] = useState('');
  const [reports, setReports] = useState(INITIAL_REPORTS);
  const [selectedReport, setSelectedReport] = useState<ReportRow | null>(null);
  const [scheduleOpen, setScheduleOpen] = useState(false);
  const [scheduleFrequency, setScheduleFrequency] = useState('Weekly');
  const [toast, setToast] = useState('');

  const selectedCategory = REPORT_CATEGORIES.find((category) => category.id === categoryId);
  const selectedTemplate = selectedCategory?.reports.find((report) => report.id === reportId);
  const invalidDateRange = Boolean(fromDate && toDate && fromDate > toDate);
  const reportPeriod = fromDate || toDate ? `${fromDate || 'Start'} to ${toDate || 'Today'}` : 'All available dates';
  const categoryOptions = useMemo(() => [
    { value: '', label: 'Choose a report category' },
    ...REPORT_CATEGORIES.map((category) => ({ value: category.id, label: category.label }))
  ], []);
  const reportOptions = selectedCategory
    ? [{ value: '', label: 'Choose a report' }, ...selectedCategory.reports.map((report) => ({ value: report.id, label: `${report.number}. ${report.name}` }))]
    : [{ value: '', label: 'Choose a category above first' }];

  const notify = (message: string) => { setToast(message); window.setTimeout(() => setToast(''), 3000); };

  const generateReport = () => {
    if (!selectedCategory || !selectedTemplate) { notify('Choose a category and report to continue.'); return; }
    if (invalidDateRange) { notify('The From Date must be earlier than the To Date.'); return; }
    const newReport: ReportRow = {
      id: `RPT-${Date.now()}`,
      reportNumber: selectedTemplate.number,
      name: selectedTemplate.name,
      generatedBy: 'Current User',
      date: displayDate(new Date()),
      format: FORMAT_LABEL[format],
      size: estimateSize(format),
      category: selectedCategory.label,
      period: reportPeriod,
      description: selectedTemplate.description,
      status: 'Ready'
    };
    setReports((current) => [newReport, ...current]);
    notify(`${newReport.name} created in this frontend preview.`);
  };

  const exportReportList = () => {
    const rows = [
      ['#', 'Report Name', 'Category', 'Generated By', 'Date', 'Period', 'Format', 'Size', 'Status'],
      ...reports.map((report) => [report.reportNumber, report.name, report.category, report.generatedBy, report.date, report.period, report.format, report.size, report.status])
    ];
    const csv = rows.map((row) => row.map((value) => `"${String(value).replace(/"/g, '""')}"`).join(',')).join('\n');
    const link = document.createElement('a');
    link.href = URL.createObjectURL(new Blob([csv], { type: 'text/csv;charset=utf-8' }));
    link.download = 'administrative-control-reports.csv';
    link.click();
    window.setTimeout(() => URL.revokeObjectURL(link.href), 0);
    notify('Report register exported as CSV.');
  };

  const downloadReportSummary = (report: ReportRow) => {
    const previewRows = buildReportPreviewRows(report);
    const rows = [
      ['Report', report.name],
      ['Category', report.category],
      ['Period', report.period],
      [],
      ['Record ID', 'Entity / Scope', 'Result', 'Measure'],
      ...previewRows.map((row) => [row.recordId, row.entity, row.result, row.measure])
    ];
    const csv = rows.map((row) => row.map((value) => `"${String(value ?? '').replace(/"/g, '""')}"`).join(',')).join('\n');
    const link = document.createElement('a');
    link.href = URL.createObjectURL(new Blob([csv], { type: 'text/csv;charset=utf-8' }));
    link.download = `${report.name.toLowerCase().replace(/[^a-z0-9]+/g, '-')}-preview.csv`;
    link.click();
    window.setTimeout(() => URL.revokeObjectURL(link.href), 0);
    notify('Report data preview downloaded as CSV.');
  };

  const openSchedule = () => {
    if (!selectedCategory || !selectedTemplate) { notify('Choose a category and report before scheduling.'); return; }
    if (invalidDateRange) { notify('The From Date must be earlier than the To Date.'); return; }
    setScheduleOpen(true);
  };

  const saveSchedule = () => {
    if (!selectedCategory || !selectedTemplate) return;
    const scheduledReport: ReportRow = {
      id: `SCH-${Date.now()}`,
      reportNumber: selectedTemplate.number,
      name: selectedTemplate.name,
      generatedBy: 'Current User',
      date: displayDate(new Date()),
      format: FORMAT_LABEL[format],
      size: '—',
      category: selectedCategory.label,
      period: `${scheduleFrequency} · ${reportPeriod}`,
      description: selectedTemplate.description,
      status: 'Scheduled'
    };
    setReports((current) => [scheduledReport, ...current]);
    setScheduleOpen(false);
    notify(`${scheduleFrequency} schedule added in this frontend preview.`);
  };

  const columns = [
    { key: 'name', header: 'Report Name', render: (row: ReportRow) => <div><span className="font-medium text-slate-800">{row.name}</span><span className="mt-1 block text-[11px] text-slate-400">#{row.reportNumber}</span></div> },
    { key: 'category', header: 'Category', render: (row: ReportRow) => <span className="text-xs text-slate-600">{row.category.replace(/^CATEGORY \d+: /, '')}</span> },
    { key: 'generatedBy', header: 'Generated By' },
    { key: 'date', header: 'Date' },
    { key: 'format', header: 'Format', render: (row: ReportRow) => <Badge variant={row.status === 'Scheduled' ? 'warning' : 'secondary'}>{row.status === 'Scheduled' ? 'Scheduled' : row.format}</Badge> },
    { key: 'size', header: 'Size' },
    { key: 'actions', header: 'Actions', render: (row: ReportRow) => <div className="flex items-center gap-1"><Button variant="ghost" size="xs" onClick={() => setSelectedReport(row)}><Eye className="h-3.5 w-3.5" /> View</Button><Button variant="ghost" size="xs" onClick={() => downloadReportSummary(row)} disabled={row.status === 'Scheduled'}><Download className="h-3.5 w-3.5" /> Data CSV</Button></div> }
  ];

  return (
    <div className="min-h-full space-y-6 bg-slate-50 p-4 md:p-6">
      <div className="flex flex-col justify-between gap-4 md:flex-row md:items-center">
        <div>
          <div className="mb-1 text-xs text-slate-500">Administration / <span className="text-indigo-700">Administrative Control Reports</span></div>
          <h1 className="text-2xl font-bold text-slate-900">Administrative Control Reports</h1>
          <p className="mt-1 text-sm text-slate-500">Choose a report category first, then select one of its reports to configure a preview or schedule.</p>
        </div>
        <Button variant="outline" leftIcon={<Download className="h-4 w-4" />} onClick={exportReportList}>Export report register</Button>
      </div>

      <div className="grid grid-cols-1 gap-4 sm:grid-cols-3">
        <Card className="p-4"><div className="flex items-center gap-3"><span className="rounded-lg bg-indigo-50 p-2.5 text-indigo-700"><ListFilter className="h-5 w-5" /></span><div><p className="text-xs text-slate-500">Report categories</p><p className="text-xl font-semibold text-slate-900">{REPORT_CATEGORIES.length}</p></div></div></Card>
        <Card className="p-4"><div className="flex items-center gap-3"><span className="rounded-lg bg-blue-50 p-2.5 text-blue-700"><FileText className="h-5 w-5" /></span><div><p className="text-xs text-slate-500">Available report templates</p><p className="text-xl font-semibold text-slate-900">{TOTAL_REPORT_TEMPLATES}</p></div></div></Card>
        <Card className="p-4"><div className="flex items-center gap-3"><span className="rounded-lg bg-emerald-50 p-2.5 text-emerald-700"><BarChart3 className="h-5 w-5" /></span><div><p className="text-xs text-slate-500">Generated / scheduled locally</p><p className="text-xl font-semibold text-slate-900">{reports.length}</p></div></div></Card>
      </div>

      <div className="grid grid-cols-1 gap-6 xl:grid-cols-3">
        <Card title="Quick Report Generation" className="xl:col-span-1">
          <div className="space-y-4">
            <Select
              label="Report Category"
              value={categoryId}
              onChange={(value: string) => { setCategoryId(value); setReportId(''); }}
              options={categoryOptions}
            />
            <Select
              label="Reports"
              value={reportId}
              onChange={(value: string) => setReportId(value)}
              options={reportOptions}
            />
            <div className="grid grid-cols-1 gap-2 sm:grid-cols-2">
              <Input type="date" label="From Date" value={fromDate} onChange={(event) => setFromDate(event.target.value)} />
              <Input type="date" label="To Date" value={toDate} onChange={(event) => setToDate(event.target.value)} />
            </div>
            {invalidDateRange && <p className="text-xs text-red-600">From Date must be earlier than To Date.</p>}
            <Select label="Format" value={format} onChange={(value: string) => setFormat(value as ReportFormat)} options={FORMAT_OPTIONS} />
            <div className="rounded-lg border border-indigo-100 bg-indigo-50 p-3 text-xs leading-relaxed text-indigo-900">
              {selectedTemplate ? <><Layers className="mr-1 inline h-3.5 w-3.5" />{selectedTemplate.description}</> : selectedCategory ? <><ShieldCheck className="mr-1 inline h-3.5 w-3.5" />{selectedCategory.description} Select a report below to preview its details.</> : <><Layers className="mr-1 inline h-3.5 w-3.5" />Select a category, then choose a report from that category.</>}
            </div>
            <div className="flex flex-col gap-2 pt-1 sm:flex-row">
              <Button onClick={generateReport} className="flex-1" disabled={!selectedTemplate || invalidDateRange}><FileText className="h-4 w-4" /> Generate Report</Button>
              <Button variant="outline" onClick={openSchedule} className="flex-1" disabled={!selectedTemplate || invalidDateRange}><Calendar className="h-4 w-4" /> Schedule</Button>
            </div>
          </div>
        </Card>

        <Card title="Recent Reports" className="overflow-hidden xl:col-span-2" headerAction={<Badge variant="info">{reports.length} reports</Badge>}>
          <Table columns={columns} data={reports} emptyMessage="No reports have been generated yet." />
        </Card>
      </div>

      <div className="flex flex-wrap items-center justify-between gap-3 rounded-lg border border-slate-200 bg-white px-4 py-3 text-xs text-slate-500">
        <span><Clock3 className="mr-1 inline h-3.5 w-3.5 text-slate-400" />Report generation shown as a frontend preview; no live ERP data source is connected.</span>
        <span className="flex items-center gap-1"><CheckCircle2 className="h-3.5 w-3.5 text-emerald-600" />View shows sample report rows and key measures for the selected period.</span>
      </div>

      <Modal isOpen={Boolean(selectedReport)} onClose={() => setSelectedReport(null)} title={selectedReport?.name || 'Report preview'} size="lg" footer={selectedReport ? <div className="flex justify-end gap-2"><Button variant="outline" onClick={() => downloadReportSummary(selectedReport)}><Download className="h-4 w-4" /> Download data CSV</Button><Button onClick={() => setSelectedReport(null)}>Close</Button></div> : null}>
        {selectedReport && <div className="space-y-4">
          <div className="flex flex-wrap gap-2"><Badge variant={selectedReport.status === 'Scheduled' ? 'warning' : 'success'}>{selectedReport.status}</Badge><Badge variant="outline">#{selectedReport.reportNumber}</Badge><Badge variant="secondary">{selectedReport.category.replace(/^CATEGORY \d+: /, '')}</Badge></div>
          <p className="text-sm leading-relaxed text-slate-600">{selectedReport.description}</p>
          <div className="grid grid-cols-2 gap-3 rounded-xl bg-slate-50 p-4 text-sm md:grid-cols-4">
            <div><p className="text-xs text-slate-400">Reporting period</p><p className="mt-1 font-medium text-slate-800">{selectedReport.period}</p></div>
            <div><p className="text-xs text-slate-400">Output format</p><p className="mt-1 font-medium text-slate-800">{selectedReport.format}</p></div>
            <div><p className="text-xs text-slate-400">Records in scope</p><p className="mt-1 font-medium text-slate-800">1,284</p></div>
            <div><p className="text-xs text-slate-400">Items flagged</p><p className="mt-1 font-medium text-amber-700">18</p></div>
          </div>
          <section className="overflow-hidden rounded-xl border border-slate-200">
            <div className="flex flex-wrap items-center justify-between gap-2 border-b border-slate-200 bg-slate-50 px-4 py-3"><div><h3 className="text-sm font-semibold text-slate-900">Report data preview</h3><p className="mt-0.5 text-xs text-slate-500">{selectedReport.name} · {selectedReport.period}</p></div><Badge variant="info">3 sample rows</Badge></div>
            <div className="overflow-x-auto"><table className="w-full min-w-[620px] text-left text-xs"><thead className="bg-white text-[10px] uppercase tracking-wide text-slate-500"><tr><th className="p-3">Record ID</th><th className="p-3">Entity / Scope</th><th className="p-3">Result</th><th className="p-3">Measure</th></tr></thead><tbody className="divide-y divide-slate-100">{buildReportPreviewRows(selectedReport).map((row) => <tr key={row.recordId}><td className="p-3 font-mono text-slate-500">{row.recordId}</td><td className="p-3 font-medium text-slate-800">{row.entity}</td><td className="p-3"><span className={`rounded-full px-2 py-1 text-[10px] font-semibold ${row.result === 'Complete' ? 'bg-emerald-50 text-emerald-700' : 'bg-amber-50 text-amber-700'}`}>{row.result}</span></td><td className="p-3 text-slate-700">{row.measure}</td></tr>)}</tbody></table></div>
          </section>
          <div className="rounded-lg border border-indigo-100 bg-indigo-50 p-4 text-xs leading-relaxed text-indigo-900"><Eye className="mr-1 inline h-3.5 w-3.5" />Illustrative frontend report rows are shown here. Connect a live ERP data source to load the underlying production records.</div>
        </div>}
      </Modal>

      <Modal isOpen={scheduleOpen} onClose={() => setScheduleOpen(false)} title="Schedule report" size="sm" footer={<div className="flex justify-end gap-2"><Button variant="outline" onClick={() => setScheduleOpen(false)}>Cancel</Button><Button onClick={saveSchedule}><Calendar className="h-4 w-4" /> Save schedule</Button></div>}>
        <div className="space-y-4"><p className="text-sm text-slate-600">Schedule <strong>{selectedTemplate?.name}</strong> for recurring generation.</p><Select label="Frequency" value={scheduleFrequency} onChange={setScheduleFrequency} options={[{ value: 'Daily', label: 'Daily' }, { value: 'Weekly', label: 'Weekly' }, { value: 'Monthly', label: 'Monthly' }, { value: 'Quarterly', label: 'Quarterly' }]} /><p className="text-xs text-slate-400">Scheduled reports are recorded locally in this preview; no email or background job is created.</p></div>
      </Modal>

      {toast && <div role="status" className="fixed bottom-5 right-5 z-50 flex items-center gap-2 rounded-xl bg-slate-900 px-4 py-3 text-sm text-white shadow-xl"><CheckCircle2 className="h-4 w-4 text-emerald-300" />{toast}<button onClick={() => setToast('')} aria-label="Dismiss notification"><X className="ml-2 h-3.5 w-3.5" /></button></div>}
    </div>
  );
}

export default AdministrativeControlReports;
